// KPI 지표 계산 함수
export function calculateInventoryKPIs(materials: MaterialItem[]) {
  const totalItems = materials.length;
  const commonC4Count = materials.filter(m => m.commonLevel === 'C4').length;
  const commonC3Count = materials.filter(m => m.commonLevel === 'C3').length;
  const commonC2Count = materials.filter(m => m.commonLevel === 'C2').length;
  const dedicatedCount = materials.filter(m => m.commonLevel === 'DEDICATED').length;

  const totalStockValue = materials.reduce((sum, m) => sum + m.currentStock * m.unitPrice, 0);
  const itemsNeedingOrder = materials.filter(m => m.currentStock <= m.reorderPoint);
  const totalOrderValue = itemsNeedingOrder.reduce((sum, m) => sum + m.eoq * m.unitPrice, 0);

  // 공용화율
  const commonTotal = commonC4Count + commonC3Count + commonC2Count;
  const commonRatio = Math.round((commonTotal / totalItems) * 100);

  // 공통 자재 연간 구매액 및 절감 예상액
  const commonItemsAnnualSpend = materials
    .filter(m => m.isCommon)
    .reduce((sum, m) => sum + (m.dailyUsage * 300 * m.unitPrice), 0);
  const estimatedAnnualSavings = Math.round(commonItemsAnnualSpend * 0.148);

  return {
    totalItems,
    commonC4Count,
    commonC3Count,
    commonC2Count,
    dedicatedCount,
    commonTotal,
    commonRatio,
    totalStockValue,
    itemsNeedingOrderCount: itemsNeedingOrder.length,
    totalOrderValue,
    commonItemsAnnualSpend,
    estimatedAnnualSavings,
  };
}
